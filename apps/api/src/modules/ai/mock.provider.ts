import { type AiProvider, type GenerateTextParams } from './provider.interface';
import { AppError } from '../../shared/errors/AppError';

export interface MockProviderOptions {
  configured?: boolean;
  simulateTimeout?: boolean;
  simulateError?: boolean;
  fixedResponse?: string;
}

export class MockAiProvider implements AiProvider {
  readonly name = 'mock';
  public configured: boolean;
  public simulateTimeout: boolean;
  public simulateError: boolean;
  public fixedResponse?: string;

  constructor(options: MockProviderOptions = {}) {
    this.configured = options.configured ?? true;
    this.simulateTimeout = options.simulateTimeout ?? false;
    this.simulateError = options.simulateError ?? false;
    this.fixedResponse = options.fixedResponse;
  }

  async isConfigured(): Promise<boolean> {
    return this.configured;
  }

  async generateText(params: GenerateTextParams): Promise<string> {
    if (!this.configured) {
      throw new AppError(
        'AI Assistant is not configured. Please configure an API key in System Settings.',
        503,
        'AI_NOT_CONFIGURED'
      );
    }

    if (this.simulateTimeout) {
      throw new AppError('AI provider request timed out after 10 seconds', 504, 'AI_TIMEOUT');
    }

    if (this.simulateError) {
      throw new AppError('Simulated upstream AI provider failure', 502, 'AI_PROVIDER_ERROR');
    }

    if (this.fixedResponse) {
      return this.fixedResponse;
    }

    const promptLower = params.prompt.toLowerCase();

    // Contextual responses based on prompt keywords
    if (promptLower.includes('draft') || promptLower.includes('email draft')) {
      return `### Incident Escalation Update

**Subject:** [ESCALATION] Critical Operational Status Update

Dear Operations Stakeholders,

This is an automated escalation advisory regarding the active operational incident. 

**Incident Summary:**
- Severity: CRITICAL
- Current Status: Under Active Investigation
- Target SLA Window: Approaching or in Breach

**Current Actions:**
Engineering and Operations teams are actively investigating root causes. Further updates will follow as triage progresses.

*Generated by Newtonite AI Operations Assistant. Pending operator review before dispatch.*`;
    }

    if (
      promptLower.includes('summarize') ||
      promptLower.includes('cause') ||
      promptLower.includes('incident') ||
      promptLower.includes('investigate')
    ) {
      return `### Incident Briefing & Root Cause Hypothesis

**Confirmed Facts:**
- The incident was registered with high operational priority.
- State transitions and audit activity events reflect active operator engagement.

**AI Hypotheses (Unconfirmed):**
- Potential downstream connectivity degradation or timeout cascade between microservices.
- Resource contention during batch operations or high concurrency traffic bursts.

**Actionable Next Steps:**
1. Check latency spikes and error logs in upstream gateways.
2. Confirm whether recent database migrations coincided with incident onset.
3. Execute health and readiness probes on backend cluster.`;
    }

    if (promptLower.includes('overdue') || promptLower.includes('urgent')) {
      return `### Operational Assessment: Urgent & Overdue Items

Based on the verified database snapshot:
- High-priority items requiring immediate operator action have been identified.
- Please inspect active tickets in the Urgent Attention Queue.

**Confirmed Facts:**
- SLA calculation derivations derive deterministically from work item priority deadlines.
- Overdue items have surpassed their contractual resolution window.

**Actionable Next Steps:**
1. Triage unassigned critical incidents immediately.
2. Notify designated team leads of overdue breaches.
3. Review blocked dependencies on affected services.`;
    }

    if (
      promptLower.includes('approaching') ||
      promptLower.includes('deadline') ||
      promptLower.includes('sla deadline') ||
      promptLower.includes('at_risk')
    ) {
      return `### SLA Threat Advisory: Approaching Deadlines

**Confirmed Facts:**
- Items in AT_RISK state have less than 25% remaining resolution window.
- Escalation policies trigger automated notifications upon boundary breach.

**Actionable Next Steps:**
1. Reassign approaching items to active operators.
2. Validate whether Lead approval is pending in the review queue.`;
    }

    return `### Newtonite AI Operations Assistant

**Operational Findings:**
The operational context has been processed using verified server-side data.

**Key Observations:**
- All work-item references strictly adhere to team authorization boundaries.
- No confidential credentials or uncontained instructions were executed.

**Recommended Actions:**
- Consult the Work Items Registry for real-time progress.
- Engage assigned team leads for critical approvals.`;
  }
}
